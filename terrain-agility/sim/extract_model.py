"""Extract the leg kinematics, masses and collision shapes from the Pupper v3 MuJoCo model
into terrain/pupper_model.py (a plain-Python module, so the robot needs no MuJoCo).

    python3 sim/extract_model.py /path/to/pupper_v3_description/description/mujoco_xml/pupper_v3_complete.position.xml
"""
import pprint
import sys
from pathlib import Path

import mujoco
import numpy as np

LEGS = ["front_r", "front_l", "back_r", "back_l"]


def main(xml):
    m = mujoco.MjModel.from_xml_path(xml)

    def bid(n):
        return mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_BODY, n)

    def jid(n):
        return mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, n)

    base = bid("base_link")
    out = {
        "body": {
            "mass": float(m.body_mass[base]),
            "com": [float(v) for v in m.body_ipos[base]],
        },
        "legs": {},
    }
    for g in range(m.ngeom):
        if m.geom_bodyid[g] == base and m.geom_type[g] == mujoco.mjtGeom.mjGEOM_BOX:
            out["body"]["box_pos"] = [float(v) for v in m.geom_pos[g]]
            out["body"]["box_quat"] = [float(v) for v in m.geom_quat[g]]
            out["body"]["box_size"] = [float(v) for v in m.geom_size[g]]
    for leg in LEGS:
        links = []
        for i in (1, 2, 3):
            b = bid(f"leg_{leg}_{i}")
            j = jid(f"leg_{leg}_{i}")
            assert m.jnt_bodyid[j] == b
            assert np.allclose(m.jnt_pos[j], 0) and np.allclose(m.jnt_axis[j], [0, 0, 1])
            links.append({
                "pos": [float(v) for v in m.body_pos[b]],
                "quat": [float(v) for v in m.body_quat[b]],
                "mass": float(m.body_mass[b]),
                "com": [float(v) for v in m.body_ipos[b]],
                "range": [float(v) for v in m.jnt_range[j]],
            })
        s = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_SITE, f"leg_{leg}_3_foot_site")
        foot = [float(v) for v in m.site_pos[s]]
        knee_geom = None
        foot_r = None
        for g in range(m.ngeom):
            if m.geom_bodyid[g] == bid(f"leg_{leg}_2") and m.geom_type[g] == mujoco.mjtGeom.mjGEOM_CYLINDER:
                knee_geom = {"radius": float(m.geom_size[g][0]), "half_length": float(m.geom_size[g][1])}
            if m.geom_bodyid[g] == bid(f"leg_{leg}_3") and m.geom_type[g] == mujoco.mjtGeom.mjGEOM_SPHERE:
                foot_r = float(m.geom_size[g][0])
        out["legs"][leg] = {"links": links, "foot": foot, "foot_radius": foot_r, "knee": knee_geom}
    dst = Path(__file__).resolve().parent.parent / "terrain" / "pupper_model.py"
    dst.write_text(
        '"""Pupper v3 kinematic and mass parameters. GENERATED by sim/extract_model.py from\n'
        'pupper_v3_description (mujoco_xml/pupper_v3_complete.position.xml). Do not edit by hand."""\n\n'
        "MODEL = " + pprint.pformat(out, width=110, sort_dicts=False) + "\n"
    )
    print("wrote", dst)


if __name__ == "__main__":
    main(sys.argv[1])
